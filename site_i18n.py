def summary_en(slug: str, rooms: list[str]) -> str:
    head = SUMMARY_HEAD_EN[slug]
    names = [r for r in rooms if r not in GENERIC_ROOMS]
    if not names:
        return head
    return f"{head} Rooms: {', '.join(ROOMS_EN.get(n, n) for n in names)}."
